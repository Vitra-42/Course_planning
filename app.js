/* =========================================================
   СОЗДАНИЕ СТИКЕРА
========================================================= */

function createSticker(data, index) {

    const sticker = document.createElement("div");

    sticker.className = "sticker";

    sticker.dataset.index = index;

    sticker.dataset.flipped = "false";


    /* =====================================================
       ПОЗИЦИЯ
    ===================================================== */

    const boardWidth = board.clientWidth;
    const boardHeight = board.clientHeight;

    const stickerWidth = 170;
    const stickerHeight = 135;

    const x =
        Math.random() *
        Math.max(20, boardWidth - stickerWidth - 20);

    const y =
        Math.random() *
        Math.max(20, boardHeight - stickerHeight - 20);

    const rotation =
        Math.random() * 14 - 7;

    sticker.style.left = `${x}px`;
    sticker.style.top = `${y}px`;
    sticker.style.transform = `rotate(${rotation}deg)`;


    /* =====================================================
       HTML

       ВАЖНО:
       Обратная сторона НЕ зависит от backface-visibility.
       Обе стороны существуют как обычные элементы.
    ===================================================== */

    sticker.innerHTML = `

        <div class="sticker-inner">

            <div class="sticker-front">

                <div class="front-text">
                    ${data.text}
                </div>

            </div>


            <div class="sticker-back">

                <div class="back-title">
                    ${data.title}
                </div>


                <div class="mindmap">

                    <div class="mind-root">
                        ${data.title}
                    </div>


                    <div class="mind-branches">

                        ${data.nodes.map(node => `

                            <div class="mind-node">
                                ${node}
                            </div>

                        `).join("")}

                    </div>


                    <div class="mind-actions">
                        ${data.actions}
                    </div>

                </div>

            </div>

        </div>

    `;


    /* =====================================================
       ПОЛУЧАЕМ ОБЕ СТОРОНЫ
    ===================================================== */

    const inner =
        sticker.querySelector(".sticker-inner");

    const front =
        sticker.querySelector(".sticker-front");

    const back =
        sticker.querySelector(".sticker-back");


    /* =====================================================
       НАЧАЛЬНОЕ СОСТОЯНИЕ

       Обратная сторона существует,
       но скрыта.
    ===================================================== */

    back.style.display = "none";
    front.style.display = "flex";


    /* =====================================================
       КЛИК
    ===================================================== */

    sticker.addEventListener("click", function(event) {

        event.stopPropagation();


        const isFlipped =
            sticker.dataset.flipped === "true";


        if (!isFlipped) {

            /* =============================================
               ОТКРЫВАЕМ
            ============================================= */

            sticker.dataset.flipped = "true";

            sticker.classList.add("flipped");

            flippedCount++;

            counter.textContent = flippedCount;


            /* Сначала увеличиваем */

            inner.style.transform =
                "scale(1.8)";


            /* Затем переключаем сторону */

            setTimeout(() => {

                front.style.display = "none";

                back.style.display = "flex";

            }, 250);

        } else {

            /* =============================================
               ЗАКРЫВАЕМ
            ============================================= */

            sticker.dataset.flipped = "false";

            sticker.classList.remove("flipped");

            flippedCount--;

            counter.textContent = flippedCount;


            /* Сначала скрываем обратную сторону */

            back.style.display = "none";

            front.style.display = "flex";


            /* Возвращаем размер */

            inner.style.transform =
                "scale(1)";

        }


        createSparkle(
            event.clientX,
            event.clientY
        );

    });


    /* =====================================================
       HOVER
    ===================================================== */

    sticker.addEventListener("mouseenter", function() {

        if (
            sticker.dataset.flipped !== "true"
        ) {

            inner.style.transform =
                "translateY(-9px) scale(1.04)";

        }

    });


    sticker.addEventListener("mouseleave", function() {

        if (
            sticker.dataset.flipped !== "true"
        ) {

            inner.style.transform =
                "scale(1)";

        }

    });


    return sticker;
}


/* =========================================================
   ЭФФЕКТ ✦
========================================================= */

function createSparkle(x, y) {

    const sparkle =
        document.createElement("div");

    sparkle.className = "sparkle";

    sparkle.textContent =
        Math.random() > 0.5
            ? "✦"
            : "✧";

    sparkle.style.left =
        `${x}px`;

    sparkle.style.top =
        `${y}px`;

    document.body.appendChild(
        sparkle
    );

    setTimeout(() => {

        sparkle.remove();

    }, 700);

}


/* =========================================================
   СОЗДАНИЕ ВСЕХ СТИКЕРОВ
========================================================= */

function renderStickers() {

    board.innerHTML = "";

    flippedCount = 0;

    counter.textContent = "0";


    stickers.forEach(
        (data, index) => {

            const sticker =
                createSticker(
                    data,
                    index
                );

            board.appendChild(
                sticker
            );

        }
    );

}


/* =========================================================
   ЗАПУСК
========================================================= */

renderStickers();
